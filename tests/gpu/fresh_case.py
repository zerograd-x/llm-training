class Rows(Dataset):
    def __init__(self, tokens: bool):
        self.rows = ([[1, 32, 33, 2], [1, 33, 32, 2], [1, 32, 5, 2], [1, 33, 6, 2]]
                     if tokens else [[1, 4, 5, 2], [1, 6, 7, 2], [1, 8, 9, 2], [1, 10, 11, 2]])

    def __len__(self):
        return len(self.rows)

    def __getitem__(self, index):
        x = torch.tensor(self.rows[index])
        return {"input_ids": x, "attention_mask": torch.ones_like(x), "labels": x.clone()}


def collate(rows):
    return {key: torch.stack([row[key] for row in rows]) for key in rows[0]}


def environment():
    assert torch.cuda.is_available(), "A CUDA GPU is required; CPU results cannot pass"
    assert torch.cuda.device_count() == 1
    assert torch.cuda.is_bf16_supported()
    assert int(os.environ.get("WORLD_SIZE", "1")) == 1
    return {"versions": {name: metadata.version(name) for name in
                         ("torch", "deepspeed", "accelerate", "transformers", "peft", "llm-training")},
            "cuda": torch.version.cuda, "gpu": torch.cuda.get_device_name(0), "world_size": 1,
            "pid": os.getpid(), "trainer_sha256": hashlib.sha256(
                Path(inspect.getfile(Trainer)).read_bytes()).hexdigest()}


def save(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    torch.save(value, path)


def load(path):
    # These files are generated by this test suite in its new output directory.
    return torch.load(path, map_location="cpu", weights_only=False)


def snapshot(trainer):
    model = trainer.accelerator.unwrap_model(trainer.model)
    params = list(model.parameters())
    if trainer.config.deepspeed:
        import deepspeed
        context = deepspeed.zero.GatheredParameters(params, modifier_rank=None)
    else:
        context = nullcontext()
    with context:
        return {n: p.detach().cpu().clone() for n, p in model.named_parameters()}


def rng():
    return {"torch": torch.get_rng_state(), "cuda": torch.cuda.get_rng_state_all(),
            "python": random.getstate(), "numpy": np.random.get_state()}


def assert_rng(actual, expected):
    assert torch.equal(actual["torch"], expected["torch"])
    assert len(actual["cuda"]) == len(expected["cuda"])
    assert all(torch.equal(a, b) for a, b in zip(actual["cuda"], expected["cuda"]))
    assert actual["python"] == expected["python"]
    assert actual["numpy"][0] == expected["numpy"][0]
    assert np.array_equal(actual["numpy"][1], expected["numpy"][1])
    assert actual["numpy"][2:] == expected["numpy"][2:]


def optimizer_chain(optimizer):
    chain, seen = [], set()
    while optimizer is not None and id(optimizer) not in seen:
        seen.add(id(optimizer))
        chain.append(optimizer)
        optimizer = getattr(optimizer, "optimizer", None)
    return chain


class StopAtCheckpoint(RuntimeError):
    pass


class ProbeTrainer(Trainer):
    stop_after_checkpoint = False
    probe_dir = None
    trace = None

    def save_checkpoint(self):
        path = super().save_checkpoint()
        if self.state.global_step == 1 and self.stop_after_checkpoint:
            save(self.probe_dir / "checkpoint-rng.pt", rng())
            save(self.probe_dir / "checkpoint-params.pt", snapshot(self))
            save(self.probe_dir / "checkpoint-scheduler.pt", self.scheduler.state_dict())
            (self.probe_dir / "interrupt-trace.json").write_text(json.dumps(self.trace))
            raise StopAtCheckpoint()
        return path


def config(case, root, resume):
    ds = DeepSpeedConfig(zero_stage=3, offload_optimizer_device=("cpu" if case == "offload" else "none")) if ("zero3" in case or case == "offload") else None
    return TrainingConfig(
        output_dir=str(root), per_device_batch_size=1, gradient_accumulation_steps=2,
        num_epochs=1, seed=123, mixed_precision="bf16", log_every_steps=1,
        optimizer=OptimizerConfig(learning_rate=1e-2, weight_decay=0),
        scheduler=SchedulerConfig(name="linear", warmup_steps=0),
        lora=LoRAConfig(rank=4, alpha=8, target_modules=("c_attn",)) if case.startswith("lora") else None,
        trainable_tokens=TrainableTokensConfig(n_tokens_added=2) if case.startswith("tt") else None,
        gradient_checkpointing=GradientCheckpointingConfig(enabled=case.endswith("gc"), use_reentrant=False),
        deepspeed=ds, checkpoint=CheckpointConfig(save_every_steps=1, keep_last=2,
                                                resume_from="latest" if resume else None),
    )


def prepare(case, root):
    torch.manual_seed(123)
    base = GPT2LMHeadModel(GPT2Config(vocab_size=34 if case.startswith("tt") else 32,
                                    n_positions=8, n_ctx=8, n_embd=16, n_layer=1, n_head=1,
                                    bos_token_id=1, eos_token_id=2, attn_pdrop=0.1,
                                    resid_pdrop=0.1, embd_pdrop=0.1, tie_word_embeddings=True))
    base.save_pretrained(root / "base", safe_serialization=True)
    return {"base": str(root / "base")}


def clean_offload(root):
    assert "DS_SKIP_CUDA_CHECK" not in os.environ
    cuda_home = Path(os.environ["CUDA_HOME"])
    nvcc = subprocess.check_output([str(cuda_home / "bin/nvcc"), "--version"], text=True)
    assert re.search(r"release (\d+\.\d+)", nvcc).group(1) == torch.version.cuda
    # Fresh extension root is supplied by the driver; build success alone is not a train pass.
    from deepspeed.ops.op_builder import CPUAdamBuilder
    module = CPUAdamBuilder().load(verbose=True)
    return {"nvcc": nvcc, "cpuadam_module": module.__file__, "skip_cuda_check": False}


def train(case, phase, root):
    is_resume = phase == "resume"
    run_dir = root / ("baseline-run" if phase == "baseline" else "resumed-run")
    cfg = config(case, run_dir, is_resume)
    build_info = clean_offload(root) if case == "offload" else {}
    coverage = {}
    import llm_training.trainer as trainer_module
    original_builder = trainer_module.build_training_optimizer

    def audited_builder(model, conf):
        opt = original_builder(model, conf)
        expected = {id(p) for p in model.parameters() if p.requires_grad}
        actual = [id(p) for g in opt.param_groups for p in g["params"]]
        assert set(actual) == expected and len(actual) == len(set(actual))
        coverage.update(trainable_count=len(expected), optimizer_count=len(actual))
        return opt

    trainer_module.build_training_optimizer = audited_builder
    try:
        trainer = ProbeTrainer(model=AutoModelForCausalLM.from_pretrained(root / "base"),
                               train_dataset=Rows(case.startswith("tt")), collate_fn=collate, config=cfg)
    finally:
        trainer_module.build_training_optimizer = original_builder
    assert trainer.accelerator.device.type == "cuda"
    assert trainer.accelerator.num_processes == 1
    model = trainer.accelerator.unwrap_model(trainer.model)
    if cfg.deepspeed:
        assert type(trainer.model).__name__ == "DeepSpeedEngine"
        assert trainer.model.zero_optimization_stage() == 3
        assert trainer.model.bfloat16_enabled()
    if cfg.gradient_checkpointing.enabled:
        assert model.is_gradient_checkpointing and model.config.use_cache is False
    trainables = [n for n, p in model.named_parameters() if p.requires_grad]
    assert trainables
    if cfg.lora:
        assert all("lora_" in n for n in trainables)
        assert trainer.adaptation_summary.target_modules
    if cfg.trainable_tokens:
        assert all("trainable_tokens_delta" in n for n in trainables)

    if is_resume:
        assert_rng(rng(), load(root / "checkpoint-rng.pt"))
        assert (trainer.state.global_step, trainer.state.epoch, trainer.state.batch_in_epoch) == (1, 0, 2)
        current = snapshot(trainer)
        saved = load(root / "checkpoint-params.pt")
        for name in saved:
            torch.testing.assert_close(current[name], saved[name], atol=0, rtol=0)
        assert trainer.scheduler.state_dict() == load(root / "checkpoint-scheduler.pt")

    before = snapshot(trainer)
    token_before = effective_rows(trainer) if cfg.trainable_tokens else None
    chain = optimizer_chain(trainer.optimizer)
    actual_optimizer = chain[-1]
    if case == "offload":
        assert type(actual_optimizer).__name__ == "DeepSpeedCPUAdam"
    trace, seen_batches = [], []
    updates = 1 if is_resume else 0

    def pre_update(opt, args, kwargs):
        trace.append({"event": "optimizer_begin", "lr": [float(g["lr"]) for g in opt.param_groups]})

    def post_update(opt, args, kwargs):
        nonlocal updates
        updates += 1
        trace.append({"event": "optimizer_end", "updates": updates})

    h1 = actual_optimizer.register_step_pre_hook(pre_update)
    h2 = actual_optimizer.register_step_post_hook(post_update)
    original_step = trainer.scheduler.step
    raw_scheduler = getattr(trainer.scheduler, "scheduler", trainer.scheduler)

    def schedule(*args, **kwargs):
        before_epoch = raw_scheduler.last_epoch
        trace.append({"event": "scheduler_begin", "updates": updates,
                      "opt_called": bool(getattr(raw_scheduler.optimizer, "_opt_called", False)),
                      "scheduler_optimizer_is_actual": raw_scheduler.optimizer is actual_optimizer})
        result = original_step(*args, **kwargs)
        if raw_scheduler.last_epoch != before_epoch:
            assert updates > before_epoch, "Scheduler advanced before a real optimizer update"
            expected = cfg.optimizer.learning_rate * (1 - updates / 2)
            for group in actual_optimizer.param_groups:
                assert abs(float(group["lr"]) - expected) < 1e-10
        trace.append({"event": "scheduler_end", "last_epoch": raw_scheduler.last_epoch,
                      "lr": list(raw_scheduler.get_last_lr())})
        return result

    trainer.scheduler.step = schedule

    def record_batch(module, args, kwargs):
        if module.training:
            seen_batches.extend(kwargs["input_ids"].detach().cpu().tolist())

    batch_hook = trainer.model.register_forward_pre_hook(record_batch, with_kwargs=True)
    trainer.stop_after_checkpoint = phase == "interrupt"
    trainer.probe_dir, trainer.trace = root, trace
    try:
        with warnings.catch_warnings(record=True) as captured:
            warnings.simplefilter("always")
            try:
                trainer.train()
                assert phase != "interrupt", "Interrupt phase did not stop after checkpoint 1"
            except StopAtCheckpoint:
                assert phase == "interrupt" and trainer.state.global_step == 1
        messages = [str(w.message) for w in captured]
    finally:
        h1.remove(); h2.remove(); batch_hook.remove()
    after = snapshot(trainer)
    assert any(not torch.equal(before[n], after[n]) for n in trainables)
    for name in set(before) - set(trainables):
        assert torch.equal(before[name], after[name]), f"Frozen parameter changed: {name}"
    row_result = assert_token_rows(token_before, effective_rows(trainer), (32, 33)) if cfg.trainable_tokens else {}
    if phase != "interrupt":
        assert (trainer.state.global_step, trainer.state.epoch, trainer.state.batch_in_epoch) == (2, 1, 0)
        assert updates == 2 and raw_scheduler.last_epoch == 2
        assert all(abs(g["lr"]) < 1e-10 for g in actual_optimizer.param_groups)
        save(root / f"{phase}-params.pt", after)
        fixed = torch.tensor([[1, 32, 33, 2]] if cfg.trainable_tokens else [[1, 4, 5, 2]], device="cuda")
        trainer.model.eval()
        with torch.no_grad():
            logits = trainer.model(input_ids=fixed).logits.detach().float().cpu()
        assert torch.isfinite(logits).all()
        save(root / f"{phase}-logits.pt", logits)
        if cfg.lora or cfg.trainable_tokens:
            adapter = trainer.save_adapter()
            from safetensors.torch import load_file
            adapter_state = load_file(str(adapter / "adapter_model.safetensors"))
            marker = "lora_" if cfg.lora else "trainable_tokens_delta"
            assert adapter_state and all(marker in k for k in adapter_state)
            assert not (adapter / "model.safetensors").exists()
        else:
            trainer.export_model()
    return {"state": asdict(trainer.state), "trainables": trainables, "coverage": coverage,
            "optimizer_chain": [type(o).__name__ for o in chain], "trace": trace,
            "batches": seen_batches, "warnings": messages, "token_rows": row_result, **build_info}


def verify(case, root):
    baseline, resumed = load(root / "baseline-params.pt"), load(root / "resume-params.pt")
    assert set(baseline) == set(resumed)
    for name in baseline:
        torch.testing.assert_close(resumed[name], baseline[name], atol=0, rtol=0)
    results = {p: json.loads((root / f"{p}.json").read_text()) for p in ("baseline", "interrupt", "resume")}
    assert results["baseline"]["batches"] == results["interrupt"]["batches"] + results["resume"]["batches"]
    reference = load(root / "resume-logits.pt")
    torch.testing.assert_close(reference, load(root / "baseline-logits.pt"), atol=0, rtol=0)
    tokens, lora = case.startswith("tt"), case.startswith("lora")
    run = root / "resumed-run"
    fixed = torch.tensor([[1, 32, 33, 2]] if tokens else [[1, 4, 5, 2]], device="cuda")
    if tokens or lora:
        from peft import PeftModel
        base = AutoModelForCausalLM.from_pretrained(root / "base")
        adapted = PeftModel.from_pretrained(base, run / "adapter").cuda().eval()
        with torch.no_grad(), torch.autocast("cuda", dtype=torch.bfloat16):
            adapter_logits = adapted(input_ids=fixed).logits.float().cpu()
        torch.testing.assert_close(adapter_logits, reference, atol=5e-3, rtol=5e-2)
        del adapted, base
        merge = merge_trainable_tokens if tokens else merge_lora
        merged = merge(root / "base", run / "adapter", root / "merged")
        assert not (merged / "adapter_config.json").exists()
    else:
        merged = run / "final-model"
    model = AutoModelForCausalLM.from_pretrained(merged).cuda().eval()
    with torch.no_grad(), torch.autocast("cuda", dtype=torch.bfloat16):
        actual = model(input_ids=fixed).logits.float().cpu()
    assert torch.isfinite(actual).all()
    torch.testing.assert_close(actual, reference, atol=5e-3, rtol=5e-2)
    if tokens:
        base = AutoModelForCausalLM.from_pretrained(root / "base")
        original = base.get_input_embeddings().weight.detach().cpu()
        effective = model.get_input_embeddings().weight.detach().cpu()
        assert_token_rows(original, effective.to(original.dtype), (32, 33))
    return {"resume_parameter_equality": True, "data_position_equality": True,
            "reload_max_abs_error": float((actual - reference).abs().max()),
            "reload_atol": 5e-3, "reload_rtol": 5e-2}


def main() -> int:
    case, phase, destination = sys.argv[1:]
    root = Path(destination) / case
    result = {"case": case, "phase": phase, "ok": False}
    try:
        result.update(environment())
        if phase == "prepare":
            result.update(prepare(case, root))
        elif phase == "verify":
            result.update(verify(case, root))
        else:
            result.update(train(case, phase, root))
        result["ok"] = True
    except Exception as exc:
        result.update(error=repr(exc), traceback=traceback.format_exc())
        traceback.print_exc()
    finally:
        if torch.distributed.is_available() and torch.distributed.is_initialized():
            torch.distributed.destroy_process_group()
    (root / f"{phase}.json").write_text(json.dumps(result, indent=2) + "\n")
    print("RESULT " + json.dumps(result), flush=True)
    return 0 if result["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
